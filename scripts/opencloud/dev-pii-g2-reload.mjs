import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { createHash } from 'node:crypto';
import { gunzipSync } from 'node:zlib';
import { identityFromPem } from '../prod-connection-check.mjs';
import { guard, activation, MANAGEMENT_PROXY } from './dev-auto.mjs';
const mode = process.argv[2];
if (!['check','upgrade'].includes(mode)) throw Error('Explicit mode required');
const config = JSON.parse(fs.readFileSync('deploy/opencloud/dev.json'));
const peer = JSON.parse(fs.readFileSync('deploy/opencloud/prod.json'));
const rows = guard({config,peer,branch:process.env.GITHUB_REF_NAME});
if (activation(config).autoDeploy || activation(config).lovableRouting) throw Error('Activation must remain off');
const require = createRequire(path.resolve('frontend/package.json'));
const {HttpAgent,Actor}=require('@icp-sdk/core/agent');
const {IDL:I}=require('@icp-sdk/core/candid');
const {Principal}=require('@icp-sdk/core/principal');
const {Ed25519KeyIdentity}=require('@icp-sdk/core/identity');
const {Secp256k1KeyIdentity}=require('@icp-sdk/core/identity/secp256k1');
const identity=identityFromPem(fs.readFileSync(process.env.GOVERNOR_PEM_FILE,'utf8'),{Ed25519KeyIdentity,Secp256k1KeyIdentity});
if(identity.getPrincipal().toText()!==config.controllers.governor) throw Error('Wrong governor');
const agent=await HttpAgent.create({host:config.apiHost,identity,shouldFetchRootKey:false});
const B=I.Vec(I.Nat8), P=I.Principal, E=I.Vec(I.Record({name:I.Text,value:I.Text}));
const proxy=Actor.createActor(()=>I.Service({proxy:I.Func([I.Record({method:I.Text,args:B,canister_id:P,cycles:I.Nat})],[I.Variant({Ok:I.Record({result:B}),Err:I.Variant({CallFailed:I.Record({reason:I.Text}),InsufficientCycles:I.Record({available:I.Nat,required:I.Nat}),UnauthorizedUser:I.Null})})],[])}),{agent,canisterId:MANAGEMENT_PROXY});
const pid = text => Principal.fromText(text);
const call=async(method,type,arg,returns=[])=>{const r=await proxy.proxy({method,args:new Uint8Array(I.encode([type],[arg])),canister_id:pid('aaaaa-aa'),cycles:0n});if(!('Ok' in r))throw Error('Proxy refused '+method);return I.decode(returns,Uint8Array.from(r.Ok.result));};
const Target=I.Record({canister_id:P});
const Status=I.Record({module_hash:I.Opt(B),settings:I.Record({controllers:I.Vec(P),environment_variables:E,wasm_memory_limit:I.Nat})});
const status=async id=>(await call('canister_status',Target,{canister_id:pid(id)},[Status]))[0];
const hash=b=>createHash('sha256').update(b).digest('hex');
const expected=[MANAGEMENT_PROXY,config.controllers.owner,config.controllers.connectedIdentity,config.controllers.governor].sort();
const verifyControllers=s=>{if(JSON.stringify(s.settings.controllers.map(p=>p.toText()).sort())!==JSON.stringify(expected))throw Error('Controller mismatch');};


const id='fjvom-5yaaa-aaac5-aad6q-cai';
const row=rows.find(r=>r.id===id&&r.service==='pii_access_control');
if(!row||config.shared.identity_access!=='h5lly-yyaaa-aaac5-aadqq-cai')throw Error('Wrong DEV target');
const work=process.argv[3],m=JSON.parse(fs.readFileSync(path.join(work,'manifest.json')));
const a=m.canisters.find(r=>r.id===id&&r.service==='pii_access_control');
if(m.environment!=='opencloud-dev'||m.applicationKey!=='ignite_dev_v2'||!a||a.upgradePersistence!=='keep')throw Error('Wrong artifact');
const gz=fs.readFileSync(path.join(work,a.wasm)),wasm=gunzipSync(gz);
if(hash(gz)!==a.wasmSha256||hash(wasm)!==a.moduleSha256)throw Error('Artifact hash mismatch');
const verify=async()=>{const s=await status(id);verifyControllers(s);if(Buffer.from(s.module_hash[0]??[]).toString('hex')!==a.moduleSha256)throw Error('Live module differs from original artifact');const v=new Map(s.settings.environment_variables.map(x=>[x.name,x.value]));if(v.get('IGNITE_SECURE_ADULT_NAME_SAVE_RELEASE')!=='1'||v.get('IGNITE_SECURE_ADULT_NAME_IDENTITY')!==config.shared.identity_access)throw Error('Required settings missing');return s;};
const before=await verify();
console.log('Verified original G2 PII module and corrected settings');
if(mode==='check')process.exit(0);
const chunks=[];await call('clear_chunk_store',Target,{canister_id:pid(id)});
for(let i=0;i<wasm.length;i+=1000000){const chunk=wasm.subarray(i,i+1000000);const [r]=await call('upload_chunk',I.Record({canister_id:P,chunk:B}),{canister_id:pid(id),chunk},[I.Record({hash:B})]);if(Buffer.from(r.hash).toString('hex')!==hash(chunk))throw Error('Chunk mismatch');chunks.push({hash:r.hash});}
await verify();
const Upgrade=I.Record({skip_pre_upgrade:I.Opt(I.Bool),wasm_memory_persistence:I.Opt(I.Variant({keep:I.Null,replace:I.Null}))});
await call('install_chunked_code',I.Record({mode:I.Variant({upgrade:I.Opt(Upgrade)}),target_canister:P,store_canister:I.Opt(P),chunk_hashes_list:I.Vec(I.Record({hash:B})),wasm_module_hash:B,arg:B,sender_canister_version:I.Opt(I.Nat64)}),{mode:{upgrade:[{skip_pre_upgrade:[false],wasm_memory_persistence:[{keep:null}]}]},target_canister:pid(id),store_canister:[],chunk_hashes_list:chunks,wasm_module_hash:Buffer.from(a.moduleSha256,'hex'),arg:new Uint8Array(I.encode([P],[pid(config.controllers.governor)])),sender_canister_version:[]});
const after=await verify();
if(JSON.stringify(after.settings.environment_variables)!==JSON.stringify(before.settings.environment_variables)||after.settings.wasm_memory_limit!==before.settings.wasm_memory_limit)throw Error('Settings changed');
console.log('G2 PII same-module upgrade complete; settings and controllers verified');
